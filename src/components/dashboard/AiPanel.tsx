"use client";

import { useEffect, useState } from "react";
import { api } from "@/lib/api";
import type { InsightsDTO } from "@/lib/domain/types";
import { Skeleton, Spinner } from "@/components/ui";
import { Icon } from "@/components/icons";
import { Tip } from "@/components/overlays";
import { useApp } from "@/components/shell/app-context";
import { cn } from "@/lib/utils";

const SEVERITY_CLS: Record<string, string> = {
  info: "border-cyan-400/40 text-cyan-300",
  success: "border-lime-400/40 text-lime-300",
  warning: "border-amber-400/40 text-amber-300",
  danger: "border-rose-500/40 text-rose-300",
};

/**
 * Optional AI insights panel. Truthful by construction: the badge shows the
 * response's own `mode`; "ai" only appears when validated model output was used.
 * Facts and suggestions are visually separated; every item shows the evidence
 * ids it cites.
 */
export function AiPanel({ workspaceId }: { workspaceId: string }) {
  return <WorkspaceInsights key={workspaceId} workspaceId={workspaceId} />;
}

function WorkspaceInsights({ workspaceId }: { workspaceId: string }) {
  const { openTask } = useApp();
  const [data, setData] = useState<InsightsDTO | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [generation, setGeneration] = useState(0);

  function generate() {
    setLoading(true);
    setError(null);
    setGeneration((value) => value + 1);
  }

  useEffect(() => {
    let active = true;
    api<InsightsDTO>("/api/ai/insights", "POST", { workspaceId, days: 30 })
      .then((result) => { if (active) setData(result); })
      .catch((e: unknown) => {
        if (active) setError(e instanceof Error ? e.message : "Insights unavailable");
      })
      .finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [workspaceId, generation]);

  const facts = data?.insights.filter((i) => i.kind === "fact") ?? [];
  const suggestions = data?.insights.filter((i) => i.kind === "suggestion") ?? [];

  return (
    <section className="card animate-rise flex h-full flex-col p-4 sm:p-5" style={{ animationDelay: "120ms" }} data-testid="ai-panel">
      <div className="mb-3 flex items-center gap-2">
        <span className={cn("flex h-7 w-7 items-center justify-center rounded-lg", data?.mode === "ai" ? "bg-fuchsia-400/15 text-fuchsia-300" : "bg-pulse-600/15 text-pulse-300")}>
          <Icon name="sparkles" size={14} />
        </span>
        <div className="min-w-0 flex-1">
          <h3 className="panel-title text-[14px] font-semibold text-mist-100">Insights</h3>
          <p className="truncate text-[10.5px] text-mist-600" title={data?.provider}>
            {data ? (data.mode === "ai" ? `AI · ${data.provider}` : "Deterministic rule engine — no external AI in use") : "Analyzing your metrics…"}
          </p>
        </div>
        {data && (
          <Tip label={data.mode === "ai" ? "Generated by an external model from the evidence bundle; citations validated." : "Computed locally from your metrics — no external AI provider is configured or was called."}>
            <span
              className={cn(
                "cursor-help rounded-full border px-2 py-0.5 font-mono text-[9px] font-bold uppercase tracking-wider",
                data.mode === "ai" ? "border-fuchsia-400/40 bg-fuchsia-400/10 text-fuchsia-300" : "border-cyan-400/40 bg-cyan-400/10 text-cyan-300",
              )}
            >
              {data.mode}
            </span>
          </Tip>
        )}
        <button
          onClick={() => void generate()}
          disabled={loading}
          className="rounded-lg p-1.5 text-mist-500 transition-colors hover:bg-ink-700 hover:text-pulse-300 disabled:opacity-50"
          aria-label="Regenerate insights"
          title="Regenerate"
        >
          {loading ? <Spinner size={14} /> : <Icon name="refresh" size={14} />}
        </button>
      </div>

      <div className="flex-1 space-y-2.5 overflow-y-auto">
        {loading && !data ? (
          <>
            <Skeleton className="h-16 w-full" />
            <Skeleton className="h-16 w-full" />
            <Skeleton className="h-16 w-full" />
          </>
        ) : error ? (
          <p role="alert" className="rounded-lg border border-rose-500/30 bg-rose-500/10 px-3 py-2 text-[12.5px] text-rose-300">{error}</p>
        ) : data && data.insights.length === 0 ? (
          <p className="px-1 py-6 text-center text-[12.5px] text-mist-500">No notable findings for this window.</p>
        ) : (
          <>
            {facts.length > 0 && <p className="text-[10px] font-semibold uppercase tracking-[0.12em] text-mist-600">Observed</p>}
            {facts.map((ins, i) => (
              <InsightCard key={`f${i}`} ins={ins} onOpenTask={openTask} />
            ))}
            {suggestions.length > 0 && <p className="pt-1 text-[10px] font-semibold uppercase tracking-[0.12em] text-mist-600">Suggested</p>}
            {suggestions.map((ins, i) => (
              <InsightCard key={`s${i}`} ins={ins} onOpenTask={openTask} suggestion />
            ))}
            {data && data.droppedInvalid > 0 && (
              <p className="text-[10.5px] text-amber-300">
                {data.droppedInvalid} model output item(s) were rejected for missing or invalid evidence citations.
              </p>
            )}
          </>
        )}
      </div>
      <p className="mt-3 border-t border-line pt-2 text-[10px] leading-3.5 text-mist-600">
        {data?.mode === "ai"
          ? `Generated from ${data.evidenceCount} supplied evidence facts about this workspace only; citations are validated before display. Verify against the metric panels.`
          : "Every statement above is computed locally from the published formulas. Set OPENAI_API_KEY server-side to enable the optional AI provider."}
      </p>
    </section>
  );
}

function InsightCard({
  ins,
  onOpenTask,
  suggestion,
}: {
  ins: InsightsDTO["insights"][number];
  onOpenTask: (id: string) => void;
  suggestion?: boolean;
}) {
  return (
    <div
      className={cn(
        "rounded-xl border-l-2 bg-ink-800/70 py-2.5 pl-3 pr-3 animate-rise",
        SEVERITY_CLS[ins.severity],
        suggestion && "border-dashed",
      )}
      style={{ borderLeftColor: "currentColor" }}
    >
      <p className="flex items-start gap-1.5 text-[12.5px] font-semibold leading-4.5 text-mist-100">
        {suggestion && <Icon name="sparkles" size={12} className="mt-0.5 shrink-0 text-fuchsia-300" />}
        {ins.title}
      </p>
      <p className="mt-1 text-[12px] leading-[1.45] text-mist-400">{ins.body}</p>
      <div className="mt-1.5 flex flex-wrap items-center gap-1">
        {ins.evidenceRefs.map((ref) => (
          <span key={ref} className="rounded border border-line bg-ink-850 px-1 py-px font-mono text-[9px] text-mist-500" title="Cited evidence fact">
            {ref}
          </span>
        ))}
        {ins.taskIds.slice(0, 3).map((id) => (
          <button key={id} onClick={() => onOpenTask(id)} className="rounded border border-line bg-ink-850 px-1.5 py-0.5 font-mono text-[9.5px] text-pulse-300 hover:border-pulse-600">
            open task ↗
          </button>
        ))}
      </div>
    </div>
  );
}
